        $shipTo['country'] ?? ($shipTo['country_code'] ?? null),
    ]);
    $subtotal = $order->items->sum(fn ($item) => (float) $item->unit_price * $item->quantity);
    $tax = (float) $order->items->sum('tax_amount');
    // Whatever the store charged beyond the lines (shipping, fees) or took off (discounts)
