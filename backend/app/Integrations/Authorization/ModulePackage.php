<?php

namespace App\Integrations\Authorization;

use App\Enums\StorePlatform;
use App\Models\Store;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\URL;
use RuntimeException;
use ZipArchive;

/**
 * Platforms without an app approval page (PrestaShop, OpenCart) get a Finovo module built for one store.
 * Installing the module creates API access in the shop and posts it to that platform's Finovo callback.
 */
class ModulePackage
{
    /** The module links back to its store for a week, so the merchant has time to install it. */
    private const LINK_TTL_SECONDS = 604800;

    /**
     * Module source folder (under resources/integrations), file name the platform's uploader expects,
     * where the store's connection file goes inside the zip, and the constant that proves the platform loaded it.
     *
     * @var array<string, array{source: string, filename: string, connection: string, guard: string}>
     */
    private const LAYOUTS = [
        'prestashop' => [
            'source' => 'prestashop',
            'filename' => 'finovo.zip',
            'connection' => 'finovo/connection.php',
            'guard' => '_PS_VERSION_',
        ],
        'opencart' => [
            'source' => 'opencart',
            'filename' => 'finovo.ocmod.zip',
            'connection' => 'upload/system/library/finovo/connection.php',
            'guard' => 'DIR_SYSTEM',
        ],
    ];

    public function __construct(
        protected AuthorizationState $state
    ) {}

    public static function supports(StorePlatform $platform): bool
    {
        return isset(self::LAYOUTS[$platform->value]);
    }

    public function canBuild(): bool
    {
        return class_exists(ZipArchive::class);
    }

    /**
     * Download link that works without a Finovo login (a plain browser download), valid for one day.
     */
    public function downloadUrl(Store $store): string
    {
        return URL::temporarySignedRoute('integrations.module.download', now()->addDay(), ['store' => $store->id]);
    }

    public function filename(Store $store): string
    {
        return $this->layout($store)['filename'];
    }

    /**
     * Build the module zip for this store in a temporary file and return its path.
     *
     * @throws RuntimeException
     */
    public function build(Store $store): string
    {
        $layout = $this->layout($store);
        $path = tempnam(sys_get_temp_dir(), 'finovo-module-');
        $zip = new ZipArchive;

        if ($path === false || $zip->open($path, ZipArchive::CREATE | ZipArchive::OVERWRITE) !== true) {
            throw new RuntimeException("Could not build the Finovo {$store->platform->label()} module.");
        }

        foreach (File::allFiles(resource_path('integrations/'.$layout['source'])) as $file) {
            $zip->addFile($file->getPathname(), str_replace('\\', '/', $file->getRelativePathname()));
        }

        $zip->addFromString($layout['connection'], $this->connectionFile($store, $layout['guard']));
        $zip->close();

        return $path;
    }

    /**
     * @return array{source: string, filename: string, connection: string, guard: string}
     */
    private function layout(Store $store): array
    {
        return self::LAYOUTS[$store->platform->value]
            ?? throw new RuntimeException("{$store->platform->label()} does not use a Finovo module.");
    }

    private function connectionFile(Store $store, string $guard): string
    {
        $settings = var_export([
            'callback_url' => route("integrations.{$store->platform->value}.callback"),
            'state' => $this->state->issue($store, self::LINK_TTL_SECONDS),
        ], true);

        return <<<PHP
        <?php
        // Generated by Finovo. Links this module to one Finovo store; do not share this file.
        if (!defined('{$guard}')) {
            exit;
        }

        return {$settings};

        PHP;
    }
}
